#!/usr/bin/env node
//
// Asserts that `composePreviewDaemon` in plugin-version.json is the daemon
// release the pinned plugin actually resolves.
//
// Why this gate exists: compose-ai-tools extracted the daemon, the three
// renderers, the preview annotations and the data extractors into
// yschimke/compose-preview-daemon, which versions them on its own 3.x train.
// The plugin bakes one daemon version in (`PreviewDaemonVersion`) and every POM
// it publishes imports `compose-preview-daemon-bom` at that same version, so a
// consumer naming no daemon version cannot skew from the one the plugin's
// binaries were compiled against.
//
// This repository has to name one anyway — not to resolve artifacts (it runs no
// Gradle) but to know which repository and which tag the vendored protocol
// fixtures come from. That makes `composePreviewDaemon` a *derived* pin, and a
// derived pin written by hand is a pin that silently goes stale on the next
// `composeAiPlugin` bump. So it is read back from the published POM instead of
// trusted.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const defaultRepoRoot = resolve(here, "..");

// The release BOM is always published; an unchanged module such as render-host
// can stay at an earlier version when the plugin releases.
const ANCHOR_ARTIFACT = "compose-ai-tools-bom";
const DAEMON_BOM = "compose-preview-daemon-bom";

export function pomUrl(pluginVersion) {
    return `https://repo1.maven.org/maven2/ee/schimke/composeai/${ANCHOR_ARTIFACT}/${pluginVersion}/${ANCHOR_ARTIFACT}-${pluginVersion}.pom`;
}

/**
 * Reads a module constraint or BOM import from the release BOM.
 * Deliberately a scan for the matching <dependency> element rather
 * than an XML parse: the shape is machine-generated by Gradle and a dependency
 * here would be a build dependency for a 40-line check.
 */
export function versionInBom(pom, artifactId) {
    const dependencies = [
        ...pom.matchAll(/<dependency>([\s\S]*?)<\/dependency>/g),
    ];
    const versions = new Set();
    for (const [, body] of dependencies) {
        const group = body.match(/<groupId>\s*([^<\s]+)\s*<\/groupId>/);
        const artifact = body.match(
            /<artifactId>\s*([^<\s]+)\s*<\/artifactId>/,
        );
        if (
            group?.[1] !== "ee.schimke.composeai" ||
            artifact?.[1] !== artifactId
        ) {
            continue;
        }
        const version = body.match(/<version>\s*([^<\s]+)\s*<\/version>/);
        if (version) {
            versions.add(version[1]);
        }
    }
    if (versions.size === 0) {
        return undefined;
    }
    if (versions.size > 1) {
        throw new Error(
            `imports ${artifactId} at more than one version (${[...versions].sort().join(", ")})`,
        );
    }
    return [...versions][0];
}

export function daemonBomVersionIn(pom) {
    return versionInBom(pom, DAEMON_BOM);
}

export async function fetchToolsBom(pluginVersion) {
    const url = pomUrl(pluginVersion);
    const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
    if (!response.ok) {
        throw new Error(
            `could not resolve ${ANCHOR_ARTIFACT} for pinned plugin ${pluginVersion}: ${response.status} ${response.statusText} (${url})`,
        );
    }
    return { pom: await response.text(), source: url };
}

async function readPin(repoRoot) {
    const path = resolve(repoRoot, "plugin-version.json");
    const text = await readFile(path, "utf8");
    const pin = JSON.parse(text);
    const pluginVersion = pin.composeAiPlugin;
    if (typeof pluginVersion !== "string" || pluginVersion.length === 0) {
        throw new Error(
            "plugin-version.json has no non-empty composeAiPlugin pin",
        );
    }
    return {
        path,
        text,
        pluginVersion,
        daemonVersion: pin.composePreviewDaemon,
    };
}

/** The daemon release the pinned plugin's published BOM imports. */
async function publishedDaemonVersion(pluginVersion, pom, pomSource) {
    let resolvedPom = pom;
    let resolvedSource = pomSource;
    if (resolvedPom === undefined) {
        const fetched = await fetchToolsBom(pluginVersion);
        resolvedPom = fetched.pom;
        resolvedSource = fetched.source;
    }

    let published;
    try {
        published = daemonBomVersionIn(resolvedPom);
    } catch (error) {
        throw new Error(`${resolvedSource} ${error.message}`);
    }
    if (published === undefined) {
        throw new Error(
            `${resolvedSource} imports no ${DAEMON_BOM}, so the daemon version plugin ${pluginVersion} resolves cannot be read from it. If compose-ai-tools stopped importing the BOM, this gate needs a new anchor — do not drop the check.`,
        );
    }
    return { published, source: resolvedSource };
}

export async function checkDaemonPin({
    repoRoot = defaultRepoRoot,
    pom,
    pomSource = "provided POM",
} = {}) {
    const { pluginVersion, daemonVersion } = await readPin(repoRoot);
    if (typeof daemonVersion !== "string" || daemonVersion.length === 0) {
        throw new Error(
            "plugin-version.json has no non-empty composePreviewDaemon pin; it names the yschimke/compose-preview-daemon release the pinned plugin resolves",
        );
    }

    const { published, source } = await publishedDaemonVersion(
        pluginVersion,
        pom,
        pomSource,
    );
    if (published !== daemonVersion) {
        throw new Error(
            `plugin-version.json pins composePreviewDaemon ${daemonVersion}, but plugin ${pluginVersion} resolves the daemon at ${published} (${source}). Set composePreviewDaemon to ${published} and re-run scripts/sync-protocol-fixtures.sh, or run this script with --write.`,
        );
    }

    return { pluginVersion, daemonVersion, pomSource: source };
}

/**
 * Rewrites `composePreviewDaemon` in place to the release the pinned plugin
 * resolves. Used by the `Sync daemon pin` workflow on Renovate's plugin bumps,
 * which change `composeAiPlugin` and cannot derive this second value. Only the
 * value is replaced, so the file's comments and layout survive untouched.
 */
export async function writeDaemonPin({
    repoRoot = defaultRepoRoot,
    pom,
    pomSource = "provided POM",
} = {}) {
    const { path, text, pluginVersion, daemonVersion } =
        await readPin(repoRoot);
    const { published } = await publishedDaemonVersion(
        pluginVersion,
        pom,
        pomSource,
    );
    if (published === daemonVersion) {
        return {
            pluginVersion,
            previous: daemonVersion,
            daemonVersion: published,
            changed: false,
        };
    }

    const field = /("composePreviewDaemon"\s*:\s*")[^"\n]*(")/g;
    const matches = text.match(field) ?? [];
    if (matches.length !== 1) {
        throw new Error(
            `plugin-version.json has ${matches.length} composePreviewDaemon fields; expected exactly one to rewrite`,
        );
    }
    const rewritten = text.replace(field, `$1${published}$2`);
    if (JSON.parse(rewritten).composePreviewDaemon !== published) {
        throw new Error("rewriting composePreviewDaemon did not take");
    }
    await writeFile(path, rewritten);
    return {
        pluginVersion,
        previous: daemonVersion,
        daemonVersion: published,
        changed: true,
    };
}

async function main() {
    if (process.argv.includes("--write")) {
        try {
            const result = await writeDaemonPin();
            console.log(
                result.changed
                    ? `daemon pin: plugin ${result.pluginVersion} resolves compose-preview-daemon ${result.daemonVersion}; rewrote composePreviewDaemon from ${result.previous}`
                    : `daemon pin: plugin ${result.pluginVersion} resolves compose-preview-daemon ${result.daemonVersion}; already pinned`,
            );
        } catch (error) {
            console.error(`daemon pin: FAILED — ${error.message}`);
            process.exitCode = 1;
        }
        return;
    }
    try {
        const result = await checkDaemonPin();
        console.log(
            `daemon pin: plugin ${result.pluginVersion} resolves compose-preview-daemon ${result.daemonVersion}; plugin-version.json agrees`,
        );
    } catch (error) {
        console.error(`daemon pin: FAILED — ${error.message}`);
        process.exitCode = 1;
    }
}

if (
    process.argv[1] &&
    resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
    await main();
}
